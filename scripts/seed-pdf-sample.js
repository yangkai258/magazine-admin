// scripts/seed-pdf-sample.js
// v6.2 任务：生成 sample PDF（2-3 页）写到 uploads/skeleton/sample.pdf
//
// 策略：
//   1) 优先尝试 pdf-lib（如果 node_modules 里有）
//   2) 降级：手写一个最小的合法 3 页 PDF（不用第三方库）
//
// 日志写到 scripts/seed-pdf-sample.log（sandbox 里 stdout 静默吞，但 fs.appendFileSync 没问题）
const path = require('path');
const fs = require('fs');

const logPath = path.join(__dirname, 'seed-pdf-sample.log');
function log(msg) {
  const line = '[' + new Date().toISOString() + '] ' + msg + '\n';
  try { fs.appendFileSync(logPath, line); } catch (e) {}
  try { process.stdout.write(line); } catch (e) {}
}

try { fs.unlinkSync(logPath); } catch (e) {}
log('[seed-pdf] start');

process.chdir(path.join(__dirname, '..'));

// uploads/skeleton/ 是 v6.2 新约定的 PDF 草稿图落盘目录
const targetDir = path.join(__dirname, '..', 'uploads', 'skeleton');
const targetFile = path.join(targetDir, 'sample.pdf');
try { fs.mkdirSync(targetDir, { recursive: true }); } catch (e) {
  log('[seed-pdf] mkdir failed: ' + e.message);
}

let pdfBuffer = null;
let strategy = 'unknown';

try {
  // 1) 优先 pdf-lib
  // eslint-disable-next-line global-require
  const { PDFDocument, StandardFonts, rgb } = require('pdf-lib');
  strategy = 'pdf-lib';
  log('[seed-pdf] using pdf-lib strategy');

  (async () => {
    try {
      const doc = await PDFDocument.create();
      const font = await doc.embedFont(StandardFonts.Helvetica);

      const pages = [
        { title: '2026 Q2 Quarterly', body: 'Page 1: Cover with logo and quarterly headline.' },
        { title: 'CEO Letter',        body: 'Page 2: Q2 business recap and Q3 strategic priorities.' },
        { title: 'Product Highlights', body: 'Page 3: New product launches, key features, and go-to-market timeline.' }
      ];

      for (const p of pages) {
        const page = doc.addPage([612, 792]);  // US Letter
        page.drawText(p.title, { x: 72, y: 720, size: 24, font, color: rgb(0.1, 0.1, 0.4) });
        page.drawText(p.body,  { x: 72, y: 660, size: 12, font, color: rgb(0.2, 0.2, 0.2) });
        page.drawText('(sample PDF generated by seed-pdf-sample.js for v6.2 e2e)', {
          x: 72, y: 60, size: 8, font, color: rgb(0.5, 0.5, 0.5)
        });
      }

      const bytes = await doc.save();
      pdfBuffer = Buffer.from(bytes);
      finish();
    } catch (e) {
      log('[seed-pdf] pdf-lib async failed: ' + e.message + ' — falling back to inline minimal PDF');
      strategy = 'inline-fallback';
      pdfBuffer = buildInlineSamplePdf();
      finish();
    }
  })();
} catch (e) {
  // 2) 降级：手写一个最小合法的 3 页 PDF
  log('[seed-pdf] pdf-lib not available, using inline minimal PDF strategy: ' + e.message);
  strategy = 'inline-fallback';
  pdfBuffer = buildInlineSamplePdf();
  finish();
}

function finish() {
  try {
    fs.writeFileSync(targetFile, pdfBuffer);
    const stat = fs.statSync(targetFile);
    const head = pdfBuffer.slice(0, 8).toString('ascii');
    const validPdfMagic = head.startsWith('%PDF-');
    log('[seed-pdf] wrote ' + targetFile + ' size=' + stat.size + ' bytes');
    log('[seed-pdf] strategy=' + strategy);
    log('[seed-pdf] magic_bytes="' + head.replace(/[\r\n]/g, '\\n') + '" valid=' + validPdfMagic);

    // 落一个 metadata JSON 方便后续脚本读
    const meta = {
      file: path.relative(process.cwd(), targetFile).replace(/\\/g, '/'),
      size_bytes: stat.size,
      strategy: strategy,
      valid_pdf_magic: validPdfMagic,
      created_at: new Date().toISOString(),
      note: 'v6.2 sample PDF for e2e — used by scripts/test-pdf-import.js'
    };
    fs.writeFileSync(targetFile + '.meta.json', JSON.stringify(meta, null, 2), 'utf8');
    log('[seed-pdf] wrote ' + targetFile + '.meta.json');

    log('[seed-pdf] done');
    process.exit(0);
  } catch (e) {
    log('[seed-pdf] write failed: ' + e.message);
    process.exit(1);
  }
}

// 最小合法 PDF：3 页，每页 1 行文本。
// 不用第三方库；用 Helvetica 标准字体（Type1 内置，不嵌）。
// 结构：3 个 page object + 1 个 pages root + 1 个 catalog + xref + trailer。
function buildInlineSamplePdf() {
  // 文本内容（每个 page 一条 BT/ET 文字块）
  const pageContents = [
    'BT /F1 24 Tf 72 720 Td (2026 Q2 Quarterly - Page 1) Tj ET',
    'BT /F1 24 Tf 72 720 Td (CEO Letter - Page 2) Tj ET',
    'BT /F1 24 Tf 72 720 Td (Product Highlights - Page 3) Tj ET'
  ];

  // 构造 stream 字节
  const streams = pageContents.map(s => Buffer.from(s, 'ascii'));

  // 对象编号（1-based）：
  //   1: Catalog
  //   2: Pages root
  //   3-5: Page objects
  //   6-8: Content streams
  //   9: Font (Helvetica Type1)
  const objects = new Array(10).fill(null);

  objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objects[2] = '<< /Type /Pages /Count 3 /Kids [3 0 R 4 0 R 5 0 R] >>';
  objects[3] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 9 0 R >> >> /Contents 6 0 R >>';
  objects[4] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 9 0 R >> >> /Contents 7 0 R >>';
  objects[5] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 9 0 R >> >> /Contents 8 0 R >>';

  // 拼装：header + 各 object + xref + trailer
  const header = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
  let body = '';
  const offsets = [0]; // xref[0] 保留为 free entry

  for (let i = 1; i < objects.length; i++) {
    if (objects[i] === null) continue;
    offsets[i] = Buffer.byteLength(header + body, 'binary');
    if (i >= 6 && i <= 8) {
      // content stream: << /Length N >>\nstream\n...content...\nendstream
      const contentObj = '<< /Length ' + streams[i - 6].length + ' >>\nstream\n' + streams[i - 6].toString('ascii') + '\nendstream';
      body += (i + ' 0 obj\n' + contentObj + '\nendobj\n');
    } else if (i === 9) {
      // font
      body += (i + ' 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n');
    } else {
      body += (i + ' 0 obj\n' + objects[i] + '\nendobj\n');
    }
  }

  const xrefOffset = Buffer.byteLength(header + body, 'binary');
  let xref = 'xref\n0 10\n';
  xref += '0000000000 65535 f \n';
  for (let i = 1; i < 10; i++) {
    if (objects[i] === null) {
      xref += '0000000000 65535 f \n';
    } else {
      xref += String(offsets[i]).padStart(10, '0') + ' 00000 n \n';
    }
  }
  const trailer = 'trailer\n<< /Size 10 /Root 1 0 R >>\nstartxref\n' + xrefOffset + '\n%%EOF\n';

  return Buffer.from(header + body + xref + trailer, 'binary');
}
